export type Priority = 'low' | 'medium' | 'high' | 'critical';

export type TaskStatus = 'inbox' | 'todo' | 'in_progress' | 'blocked' | 'done' | 'cancelled';

export type TaskCategory = 'project' | 'career' | 'personal' | 'routine';

export interface Task {
  id: string;
  title: string;
  description?: string;
  status: TaskStatus;
  priority: Priority;
  dueDate?: string; // YYYY-MM-DD
  dueTime?: string; // HH:mm
  reminderTime?: string; // ISO string or YYYY-MM-DD HH:mm
  estimatedEffortHours?: number;
  projectId?: string;
  careerApplicationId?: string;
  tags: string[];
  dependencies?: string[]; // IDs of tasks that must be done first
  isHardDeadline?: boolean;
  consequencesOfDelay?: string;
  isRecurring?: boolean;
  recurrenceRule?: 'daily' | 'weekdays' | 'weekly' | 'biweekly' | 'monthly';
  postponedCount?: number;
  completedAt?: string;
  createdAt: string;
  updatedAt: string;
  notes?: string;
  recommendationReason?: string; // generated by planning engine
  isRecommendedToday?: boolean;
  manualPlanOrder?: number;
}

export type JobStatus =
  | 'interested'
  | 'to_apply'
  | 'applied'
  | 'follow_up_due'
  | 'interview'
  | 'offer'
  | 'rejected'
  | 'withdrawn';

export interface JobApplication {
  id: string;
  company: string;
  role: string;
  jobUrl?: string;
  source: 'LinkedIn' | 'Naukri' | 'Company Career Page' | 'Referral' | 'Other';
  location: string;
  workArrangement: 'Remote' | 'Hybrid' | 'On-site';
  salaryNotes?: string;
  applicationDate: string; // YYYY-MM-DD
  status: JobStatus;
  resumeVersion?: string;
  recruiterName?: string;
  recruiterEmail?: string;
  recruiterPhone?: string;
  lastContactDate?: string; // YYYY-MM-DD
  nextFollowUpDate?: string; // YYYY-MM-DD
  interviewDate?: string; // YYYY-MM-DD HH:mm
  interviewStage?: string;
  notes?: string;
  createdAt: string;
  updatedAt: string;
}

export type ProjectStatus = 'planning' | 'in_progress' | 'on_hold' | 'completed' | 'archived';

export interface ProjectMilestone {
  id: string;
  title: string;
  dueDate: string;
  completed: boolean;
}

export interface Project {
  id: string;
  name: string;
  description: string;
  status: ProjectStatus;
  priority: Priority;
  startDate?: string;
  deadline?: string;
  color: string; // hex or tailwind token
  milestones: ProjectMilestone[];
  notes?: string;
  repoUrl?: string;
  liveUrl?: string;
  createdAt: string;
  updatedAt: string;
}

export interface Note {
  id: string;
  title: string;
  content: string;
  tags: string[];
  category: 'Interview Prep' | 'Career' | 'Project Doc' | 'Meeting' | 'General';
  linkedProjectId?: string;
  linkedJobId?: string;
  isPinned?: boolean;
  createdAt: string;
  updatedAt: string;
}

export interface PlanningPreferences {
  userName: string;
  userTitle: string;
  workingDays: number[]; // 0=Sun, 1=Mon, ..., 6=Sat
  dailyCapacityHours: number;
  defaultPriority: Priority;
  deadlineFlexibility: 'strict' | 'moderate' | 'relaxed';
  targetCareerBalancePercent: number; // e.g. 40% career, 60% projects
  autoReassessUnfinished: boolean;
  quote: string;
}

export interface DailyPlanProposal {
  date: string;
  recommendedTasks: Task[];
  urgentCommitments: Task[];
  recommendedWork: Task[];
  routineTasks: Task[];
  optionalWork: Task[];
  totalEstimatedHours: number;
  capacityHours: number;
  capacityExceeded: boolean;
  postponedTasksForReview: Task[];
  isApproved: boolean;
}
